import fs from 'node:fs';
const worker=fs.readFileSync('functions/[[path]].js','utf8');
const site=fs.readFileSync('public/assets/site.js','utf8');
const contracts=fs.readFileSync('functions/_shared/template-contracts.js','utf8');
const fail=(m)=>{console.error('FAIL',m);process.exit(1)};
const ok=(m)=>console.log('OK',m);
if(!worker.includes('function unifiedProfessionalDemoHtml')) fail('missing unified professional demo shell');
if(!worker.includes('window.NR_LOCAL_SHOWROOM_PACKAGE=')) fail('showroom package transport missing');
if((worker.match(/injectProClientSimulation\(proDemoHtml\(/g)||[]).length) fail('legacy professional renderer is still used by a route');
ok('professional showroom routes no longer call the legacy server renderer');
if(!site.includes('localShowroomPackage')||!site.includes('d=localShowroomPackage')) fail('client boot does not consume local showroom package');
ok('showroom and live/trial enter the same client renderer boot');
if(!site.includes("effectivePreset==='service_lion_dance_6'")) fail('lion live renderer missing');
if(!site.includes("renderLionDanceTemplate(s)")) fail('lion renderer not dispatched');
ok('Lion sample/empty/live all dispatch renderLionDanceTemplate');
if(!site.includes("typeof nrDemoUrl==='function'?nrDemoUrl(raw):raw")) fail('professional article URLs do not preserve demo/trial context');
ok('professional article links preserve the active data mode');
const keys=[...contracts.matchAll(/GLOBAL_TEMPLATE_KEYS=\[([^\]]+)\]/g)][0];
if(!keys) fail('global template registry missing');
const count=(keys[1].match(/'/g)||[]).length/2;
if(count!==21) fail('expected 21 global templates, got '+count);
ok('global registry remains 21 templates');
console.log('One Renderer / Three Data Modes V6: PASS');
